package ovakap9;

public class printstars { 
    public static void main(String[] args) { 
        printstars(5);
        
    } 
    static void printstars( int number){ 
        
        for(int i=0; i<number; i++){ 
            System.out.print("*"); 
        } 
        System.out.println();

    } 
    

}
